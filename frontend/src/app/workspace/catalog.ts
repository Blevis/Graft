export type Persona = keyof typeof roles
export interface Screen {
  id: number
  slug: string
  title: string
  role: Persona
  icon: LucideIcon
  description: string
}
function page(
  id: number,
  slug: string,
  title: string,
  role: Persona,
  icon: LucideIcon,
  description: string,
): Screen {
  return { id, slug, title, role, icon, description }
}
